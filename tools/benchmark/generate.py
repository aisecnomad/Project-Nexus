"""Generate the seeded, stratified benchmark corpus.

``python -m tools.benchmark.generate --seed 20261006 --per-surface 300 --output corpus.json``

Each surface gets the same label quotas (45% agent, 15% LLM-only, 40% none);
within a label the family is drawn uniformly at random, then the layout is
randomized. The same seed and generator source always produce the same bytes.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from collections.abc import Callable
from pathlib import Path, PurePosixPath
from typing import Any

from tools.benchmark import endpoint_cases, network_cases, repo_cases
from tools.benchmark.common import Case, Draft, Rand

QUOTAS = (("agent", 0.45), ("llm", 0.15), ("none", 0.40))
DEFAULT_SEED = 20261006
_SOURCES = ("common.py", "repo_cases.py", "endpoint_cases.py", "network_cases.py", "generate.py")

Pools = dict[str, tuple[Callable[[Rand], Draft], ...]]

POOLS: dict[str, Pools] = {
    "repo": {
        "agent": repo_cases.AGENT_FAMILIES,
        "llm": repo_cases.LLM_FAMILIES,
        "none": repo_cases.NEG_FAMILIES,
    },
    "endpoint": {
        "agent": endpoint_cases.EP_AGENT,
        "llm": endpoint_cases.EP_LLM,
        "none": endpoint_cases.EP_NEG,
    },
    "network": {
        "agent": network_cases.NET_AGENT,
        "llm": network_cases.NET_LLM,
        "none": network_cases.NET_NEG,
    },
}


def generator_digest() -> str:
    """SHA-256 over the generator sources, so a corpus names the code that made it."""
    h = hashlib.sha256()
    here = Path(__file__).parent
    for name in _SOURCES:
        h.update(name.encode() + b"\0" + (here / name).read_bytes() + b"\0")
    return h.hexdigest()


def _quota(n: int) -> list[str]:
    labels: list[str] = []
    for label, share in QUOTAS[:-1]:
        labels += [label] * round(n * share)
    labels += [QUOTAS[-1][0]] * (n - len(labels))
    return labels


def _finish(rd: Rand, surface: str, draft: Draft) -> Draft:
    if surface == "repo":
        return repo_cases.augment(rd, draft)
    if surface == "endpoint":
        return endpoint_cases.wrap(rd, draft)
    return draft


def _check_paths(case_id: str, files: dict[str, str]) -> None:
    seen: set[str] = set()
    for path in files:
        pure = PurePosixPath(path)
        if pure.is_absolute() or ".." in pure.parts or not path:
            raise ValueError(f"{case_id}: unsafe path {path!r}")
        folded = path.casefold()
        if folded in seen:
            raise ValueError(f"{case_id}: duplicate path {path!r}")
        seen.add(folded)
    for path in files:
        for parent in PurePosixPath(path).parents:
            if str(parent).casefold() in seen and str(parent) != ".":
                raise ValueError(f"{case_id}: {parent} is both a file and a directory")


def generate(seed: int = DEFAULT_SEED, per_surface: int = 300) -> list[Case]:
    if not 10 <= per_surface <= 400:
        raise ValueError("per_surface must be from 10 to 400")
    cases: list[Case] = []
    for s_index, surface in enumerate(("repo", "endpoint", "network")):
        rd = Rand(seed * 10 + s_index)
        labels = _quota(per_surface)
        rd.shuffle(labels)
        for i, label in enumerate(labels):
            family = rd.choice(POOLS[surface][label])
            draft = _finish(rd, surface, family(rd))
            if draft.label != label:
                raise AssertionError(f"{family.__name__} returned label {draft.label}, expected {label}")
            case_id = f"{surface}-{i:04d}"
            _check_paths(case_id, draft.files)
            cases.append(
                Case(
                    case_id=case_id,
                    surface=surface,
                    family=draft.family,
                    label=draft.label,
                    difficulty=draft.difficulty,
                    rationale=draft.rationale,
                    files=draft.files,
                    flows=draft.flows,
                )
            )
    return cases


def corpus_document(seed: int, per_surface: int) -> dict[str, Any]:
    cases = generate(seed, per_surface)
    return {
        "metadata": {
            "type": "synthetic-generated",
            "seed": seed,
            "per_surface": per_surface,
            "case_count": len(cases),
            "generator_sha256": generator_digest(),
            "authorship": "Generated by templates written in the ShadowScan repository; not independent.",
        },
        "cases": [c.to_json() for c in cases],
    }


def load_corpus(path: Path) -> tuple[dict[str, Any], list[Case]]:
    doc = json.loads(path.read_text(encoding="utf-8"))
    return doc["metadata"], [Case.from_json(c) for c in doc["cases"]]


def materialize(case: Case, root: Path) -> None:
    """Write a repository or endpoint case below ``root`` (which must be empty)."""
    for rel, text in case.files.items():
        target = root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        with open(target, "x", encoding="utf-8", newline="\n") as fh:
            fh.write(text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=DEFAULT_SEED)
    parser.add_argument("--per-surface", type=int, default=300)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args(argv)
    doc = corpus_document(args.seed, args.per_surface)
    data = json.dumps(doc, indent=1, sort_keys=False) + "\n"
    with open(args.output, "x", encoding="utf-8") as fh:
        fh.write(data)
    digest = hashlib.sha256(data.encode()).hexdigest()
    print(f"wrote {doc['metadata']['case_count']} cases to {args.output} (sha256 {digest})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
