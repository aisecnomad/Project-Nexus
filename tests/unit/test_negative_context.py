"""Negative-context framework: structured FP suppression for documentation,
example, and generated code paths.

Evidence in these paths is kept but discounted, parallel to how test paths
are treated. Tags and confidence caps make the discounting transparent.
"""

from __future__ import annotations

import pytest

from shadowscan.connectors.code.filesystem import (
    DOCS_MAX_CONFIDENCE,
    DOCS_WEIGHT_SCALE,
    EXAMPLE_PATH_MAX_CONFIDENCE,
    EXAMPLE_PATH_WEIGHT_SCALE,
    GENERATED_MAX_CONFIDENCE,
    GENERATED_WEIGHT_SCALE,
    NegativeContext,
    _is_docs_path,
    _is_example_path,
    _is_generated_path,
    negative_context,
)

