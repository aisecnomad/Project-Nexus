# ----------------------------------------------------------- negative_context


class TestNegativeContext:
    def test_generated_takes_priority_over_docs(self):
        ctx = negative_context("docs/generated/api.py")
        assert ctx is not None
        assert ctx.reason == "generated-code"

    def test_docs_path(self):
        ctx = negative_context("docs/guide.py")
        assert ctx is not None
        assert ctx.reason == "documentation"
        assert ctx.weight_scale == DOCS_WEIGHT_SCALE
        assert ctx.confidence_cap == DOCS_MAX_CONFIDENCE

    def test_example_path(self):
        ctx = negative_context("examples/chat.py")
        assert ctx is not None
        assert ctx.reason == "example-code"
        assert ctx.weight_scale == EXAMPLE_PATH_WEIGHT_SCALE
        assert ctx.confidence_cap == EXAMPLE_PATH_MAX_CONFIDENCE

    def test_generated_path(self):
        ctx = negative_context("generated/api.py")
        assert ctx is not None
        assert ctx.reason == "generated-code"
        assert ctx.weight_scale == GENERATED_WEIGHT_SCALE
        assert ctx.confidence_cap == GENERATED_MAX_CONFIDENCE

    def test_normal_path_returns_none(self):
        assert negative_context("src/main.py") is None

    def test_negative_context_is_frozen(self):
        ctx = NegativeContext("test", 0.5, 0.8)
        with pytest.raises(AttributeError):
            ctx.reason = "other"  # type: ignore[misc]


# ------------------------------------------------------- integration via scan


def _project(findings):
    return next((f for f in findings if f.resource_type == "project"), None)


class TestNegativeContextIntegration:
    def test_docs_only_finding_tagged_and_capped(self, tmp_path, run_connector):
        (tmp_path / "docs").mkdir()
        (tmp_path / "docs" / "guide.py").write_text(
            "from openai import OpenAI\n"
            "client = OpenAI()\n"
            "client.chat.completions.create(model='gpt-4', messages=[])\n"
        )
        findings, _ = run_connector("code.filesystem", path=str(tmp_path))
        proj = _project(findings)
        assert proj is not None
        assert "docs-only" in proj.tags
        assert proj.confidence <= DOCS_MAX_CONFIDENCE + 0.001

    def test_example_only_finding_tagged_and_capped(self, tmp_path, run_connector):
        (tmp_path / "examples").mkdir()
        (tmp_path / "examples" / "demo.py").write_text(
            "from openai import OpenAI\n"
            "client = OpenAI()\n"
            "client.chat.completions.create(model='gpt-4', messages=[])\n"
        )
        findings, _ = run_connector("code.filesystem", path=str(tmp_path))
        proj = _project(findings)
        assert proj is not None
        assert "example-code-only" in proj.tags
        assert proj.confidence <= EXAMPLE_PATH_MAX_CONFIDENCE + 0.001

    def test_generated_only_finding_tagged_and_capped(self, tmp_path, run_connector):
        (tmp_path / "generated").mkdir()
        (tmp_path / "generated" / "client.py").write_text(
            "from openai import OpenAI\n"
            "client = OpenAI()\n"
            "client.chat.completions.create(model='gpt-4', messages=[])\n"
        )
        findings, _ = run_connector("code.filesystem", path=str(tmp_path))
        proj = _project(findings)
        assert proj is not None
        assert "generated-code-only" in proj.tags
        assert proj.confidence <= GENERATED_MAX_CONFIDENCE + 0.001

    def test_mixed_normal_and_docs_not_tagged(self, tmp_path, run_connector):
        (tmp_path / "docs").mkdir()
        (tmp_path / "docs" / "guide.py").write_text("from openai import OpenAI\nclient = OpenAI()\n")
        (tmp_path / "app.py").write_text(
            "from openai import OpenAI\n"
            "client = OpenAI()\n"
            "client.chat.completions.create(model='gpt-4', messages=[])\n"
        )
        findings, _ = run_connector("code.filesystem", path=str(tmp_path))
        proj = _project(findings)
        assert proj is not None
        assert "docs-only" not in proj.tags

    def test_negative_context_metadata_recorded(self, tmp_path, run_connector):
        (tmp_path / "examples").mkdir()
        (tmp_path / "examples" / "demo.py").write_text("from openai import OpenAI\nclient = OpenAI()\n")
        (tmp_path / "app.py").write_text(
            "from openai import OpenAI\n"
            "client = OpenAI()\n"
            "client.chat.completions.create(model='gpt-4', messages=[])\n"
        )
        findings, _ = run_connector("code.filesystem", path=str(tmp_path))
        proj = _project(findings)
        assert proj is not None
        assert "negative_contexts" in proj.metadata
        assert "example-code" in proj.metadata["negative_contexts"]

    def test_evidence_annotated_with_negative_context(self, tmp_path, run_connector):
        (tmp_path / "docs").mkdir()
        (tmp_path / "docs" / "guide.py").write_text(
            "from openai import OpenAI\n"
            "client = OpenAI()\n"
            "client.chat.completions.create(model='gpt-4', messages=[])\n"
        )
        findings, _ = run_connector("code.filesystem", path=str(tmp_path))
        proj = _project(findings)
        assert proj is not None
        annotated = [e for e in proj.evidence if e.attributes.get("negative_context") == "documentation"]
        assert len(annotated) > 0

    def test_risk_score_reduced_for_docs_only(self, tmp_path, run_connector):
        from shadowscan.risk import assess

        (tmp_path / "docs").mkdir()
        (tmp_path / "docs" / "guide.py").write_text(
            "from openai import OpenAI\n"
            "client = OpenAI()\n"
            "client.chat.completions.create(model='gpt-4', messages=[])\n"
        )
        findings, _ = run_connector("code.filesystem", path=str(tmp_path))
        proj = _project(findings)
        assert proj is not None
        assert "docs-only" in proj.tags
        proj.risk = assess(proj)
        factor_reasons = [f.description for f in proj.risk.factors]
        assert any("documentation" in r for r in factor_reasons)


@pytest.mark.parametrize("extra", [{"verified_agent": False}, {"lexical_source": True}])
def test_signal_indicator_respects_semantic_verification(extra):
    from shadowscan.connectors.code.filesystem import _ProjectEvidence
    from shadowscan.signatures.loader import Signal, Signature
    from shadowscan.signatures.matcher import Match

    signature = Signature(id="framework.test", name="Test", category="framework")
    match = Match(signature, Signal(type="code", agent_indicator=True), "Agent()", 0.8, extra=extra)
    evidence = _ProjectEvidence([(match, "app.py", None)], discount_tests=True, mcp_tools={})
    assert not evidence.verified_indicator(match)
